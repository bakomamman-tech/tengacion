import { describe, expect, it } from 'vitest';
import { clearEventPaymentReference, getEventPaymentReference } from './eventPaymentCallback';

const reference = `NVB26-${'a'.repeat(24)}`;

describe('No Bad Vibes Paystack callback', () => {
  it('recognizes the reference parameter generated by our Paystack initialization', () => {
    expect(getEventPaymentReference(new URLSearchParams({ reference }))).toBe(reference);
  });

  it('recognizes the trxref parameter Paystack actually returned to the browser', () => {
    expect(getEventPaymentReference(new URLSearchParams({ trxref: reference }))).toBe(reference);
  });

  it('accepts matching reference and trxref while rejecting conflicting values', () => {
    expect(getEventPaymentReference(new URLSearchParams({ reference, trxref: reference }))).toBe(reference);
    expect(getEventPaymentReference(new URLSearchParams({
      reference, trxref: `NVB26-${'b'.repeat(24)}`,
    }))).toBe('');
  });

  it('rejects invalid and unrelated payment references', () => {
    expect(getEventPaymentReference(new URLSearchParams({ trxref: 'not-our-payment' }))).toBe('');
    expect(getEventPaymentReference(new URLSearchParams({ trxref: `NVB26-${'a'.repeat(23)}` }))).toBe('');
    expect(getEventPaymentReference(new URLSearchParams())).toBe('');
  });

  it('removes both payment parameters while retaining view and other state', () => {
    const result = clearEventPaymentReference(new URLSearchParams({
      reference, trxref: reference, view: 'mine', campaign: 'jaga',
    }));
    expect(result.get('reference')).toBeNull();
    expect(result.get('trxref')).toBeNull();
    expect(result.get('view')).toBe('mine');
    expect(result.get('campaign')).toBe('jaga');
  });
});
